def _assets_dir():
    base = getattr(sys, '_MEIPASS', None) or os.path.dirname(os.path.abspath(__file__))
    return os.path.join(base, 'assets')


def set_app_icon(root):
    """EmberCheck icon on a Tk window (title bar, taskbar, Alt+Tab) and on the windows it opens later
    (message boxes). Icons come from src/assets (generated by branding/make_icons.py). Never fails."""
    d = _assets_dir()
    try:
        if sys.platform == 'win32' and os.path.exists(os.path.join(d, 'embercheck.ico')):
            root.iconbitmap(default=os.path.join(d, 'embercheck.ico'))
    except Exception:
        pass
    try:
        import tkinter as tk
        imgs = [tk.PhotoImage(master=root, file=os.path.join(d, 'embercheck_%d.png' % s_))
                for s_ in (256, 48, 32, 16) if os.path.exists(os.path.join(d, 'embercheck_%d.png' % s_))]
        if imgs:
            root.iconphoto(True, *imgs)
            root._embercheck_icons = imgs      # keep references alive
    except Exception:
        pass


def logo(parent, size, bg=None):
    """Label showing the EmberCheck icon at about `size` pixels (largest asset not above it), or None."""
    import tkinter as tk
    d = _assets_dir()
    have = [s_ for s_ in (16, 20, 24, 32, 40, 48, 64) if os.path.exists(os.path.join(d, 'embercheck_%d.png' % s_))]
    if not have:
        return None
    pick = max([s_ for s_ in have if s_ <= size] or [min(have)])
    try:
        img = tk.PhotoImage(master=parent, file=os.path.join(d, 'embercheck_%d.png' % pick))
    except Exception:
        return None
    lab = tk.Label(parent, image=img, bg=bg or BG, bd=0, highlightthickness=0)
    lab.image = img
    return lab


def _font_family():
    return 'Segoe UI' if sys.platform == 'win32' else 'DejaVu Sans'


def _win_tweaks(root):
    """Dark title bar on Windows 10/11 (no effect elsewhere) + app icon."""
    if sys.platform != 'win32':
        return
    try:
        base = getattr(sys, '_MEIPASS', os.path.dirname(os.path.abspath(__file__)))  # PyInstaller puts data in _internal
        for ico in (os.path.join(base, 'icon.ico'), os.path.join(base, '..', 'packaging', 'icon.ico')):
            if os.path.exists(ico):
                root.iconbitmap(ico); break
    except Exception:
        pass
    try:
        import ctypes
        root.update_idletasks()
        hwnd = ctypes.windll.user32.GetParent(root.winfo_id())
        val = ctypes.c_int(1)
        for attr in (20, 19):  # DWMWA_USE_IMMERSIVE_DARK_MODE (new / old builds)
            if ctypes.windll.dwmapi.DwmSetWindowAttribute(hwnd, attr, ctypes.byref(val), ctypes.sizeof(val)) == 0:
                break
    except Exception:
        pass


def _dpi_aware():
    """Per-monitor DPI awareness on Windows so Tk gets real pixels (sharp text, correct sizes) instead of a
    bitmap-stretched 96-dpi window. Must run before the first Tk() is created."""
    if sys.platform == 'win32':
        import ctypes
        for fn in (lambda: ctypes.windll.shcore.SetProcessDpiAwareness(2),   # per-monitor (8.1+)
                   lambda: ctypes.windll.shcore.SetProcessDpiAwareness(1),   # system
                   lambda: ctypes.windll.user32.SetProcessDPIAware()):       # Vista+
            try:
                fn(); break
            except Exception:
                continue


def _setup_scaling(root):
    """Returns px(n): n design pixels (at 100 % / 96 dpi) -> real pixels. Fonts are given in points, which Tk already
    scales with `tk scaling`; every pixel size (widths, padding, wrap lengths, canvases) goes through px().
    PO_TK_SCALING=<factor> simulates Windows display scaling (1.0 = 100 %, 1.5 = 150 %) for tests."""
    sim = os.environ.get('PO_TK_SCALING')
    if sim:
        try:
            root.tk.call('tk', 'scaling', 96.0 * float(sim) / 72.0)
        except Exception:
            pass
    try:
        f = root.winfo_fpixels('1i') / 96.0
    except Exception:
        f = 1.0
    f = max(1.0, min(f, 4.0))
    return lambda n: int(round(n * f)), f


def _shot_hook(root, buttons, tag):
    """Test hook: PO_UI_SHOT=<file.png> saves a screenshot of the window and a JSON with the geometry check
    (every button fully inside the window and the window inside the screen), then closes the window."""
    path = os.environ.get('PO_UI_SHOT')
    if not path:
        return
    def go():
        root.update_idletasks(); root.update()
        x, y, w, h = root.winfo_rootx(), root.winfo_rooty(), root.winfo_width(), root.winfo_height()
        res = {'tag': tag, 'window': [x, y, w, h], 'screen': [root.winfo_screenwidth(), root.winfo_screenheight()],
               'scaling': os.environ.get('PO_TK_SCALING'), 'buttons': []}
        ok = y + h <= root.winfo_screenheight() and x + w <= root.winfo_screenwidth() and x >= 0 and y >= 0
        for b in buttons:
            bx, by, bw, bh = b.winfo_rootx(), b.winfo_rooty(), b.winfo_width(), b.winfo_height()
            inside = bx >= x and by >= y and bx + bw <= x + w and by + bh <= y + h and b.winfo_ismapped() and bh > 4
            res['buttons'].append([bx, by, bw, bh, inside]); ok = ok and inside
        res['ok'] = ok
        try:
            from PIL import ImageGrab
            ImageGrab.grab(bbox=(x, y, x + w, y + h), xdisplay=os.environ.get('DISPLAY')).save(path)
        except Exception as ex:
            res['shot_error'] = str(ex)
        with open(path + '.json', 'w') as f:
            json.dump(res, f)
        root.destroy()
    root.after(int(os.environ.get('PO_UI_SHOT_MS', '1200')), go)


def _round_rect(cv, x0, y0, x1, y1, r, **kw):
    r = max(0, min(r, (x1 - x0) / 2, (y1 - y0) / 2))
    pts = [x0 + r, y0, x1 - r, y0, x1, y0, x1, y0 + r, x1, y1 - r, x1, y1, x1 - r, y1, x0 + r, y1,
           x0, y1, x0, y1 - r, x0, y0 + r, x0, y0]
    return cv.create_polygon(pts, smooth=True, **kw)


class RoundButton:
    def __init__(self, parent, text, command, primary=False, width=150, height=34, font=None, bg=BG):
        import tkinter as tk
        import tkinter.font as tkfont
        self.cmd = command; self.primary = primary
        try:
            fo = tkfont.Font(root=parent, font=font) if font else tkfont.nametofont('TkDefaultFont')
            width = max(width, fo.measure(text) + int(fo.metrics('linespace') * 1.6))
            height = max(height, int(fo.metrics('linespace') * 1.9))
        except Exception:
            pass
        self.cv = tk.Canvas(parent, width=width, height=height, bg=bg, highlightthickness=0, bd=0, cursor='hand2')
        self.base = GREEN if primary else CARD
        self.hover = GREEN_HI if primary else LINE
        self.shape = _round_rect(self.cv, 1, 1, width - 1, height - 1, 9, fill=self.base,
                                 outline='' if primary else LINE)
        self.label = self.cv.create_text(width / 2, height / 2, text=text, fill='#ffffff' if primary else FG, font=font)
        self.cv.bind('<Enter>', lambda e: self.cv.itemconfig(self.shape, fill=self.hover))
        self.cv.bind('<Leave>', lambda e: self.cv.itemconfig(self.shape, fill=self.base))
        self.cv.bind('<Button-1>', lambda e: self.cmd())

    def set_text(self, t):
        self.cv.itemconfig(self.label, text=t)

    def pack(self, **kw):
        self.cv.pack(**kw); return self


class ProgressBar:
    def __init__(self, parent, width=380, height=10):
        import tkinter as tk
        self.w, self.h = width, height
        self.cv = tk.Canvas(parent, width=width, height=height, bg=BG, highlightthickness=0, bd=0)
        _round_rect(self.cv, 0, 0, width, height, height / 2, fill=TRACK, outline='')
        self.bar = None; self.set(0.0)

    def set(self, frac):
        if self.bar is not None:
            self.cv.delete(self.bar)
        x1 = max(self.h, self.w * max(0.0, min(1.0, frac)))
        self.bar = _round_rect(self.cv, 0, 0, x1, self.h, self.h / 2, fill=GREEN, outline='')


def _usable_height(root):
    """Screen height minus a taskbar allowance (Tk cannot see the work area on every platform)."""
    return root.winfo_screenheight() - int(root.winfo_fpixels('1i') * 0.6)


def _center(root, w, h, pos=None):
    root.update_idletasks()
    sw, sh = root.winfo_screenwidth(), _usable_height(root)
    w = min(w, sw); h = min(h, sh)
    if pos:
        x, y = pos
    else:
        x = (sw - w) // 2; y = (sh - h) // 2
    x = max(0, min(x, sw - w)); y = max(0, min(y, sh - h))
    root.geometry('%dx%d+%d+%d' % (w, h, x, y))


STAGE_ORDER = ['Parsing G-code', 'Thermal analysis', 'Optimizing', 'Verifying', 'Writing']


class ProgressWindow:
    """Run `work(progress_cb, cancel_flag)` in a worker thread while showing progress.
    Returns (result, error, cancelled, window_position)."""
    W, H = 460, 200

    def __init__(self, title_file=''):
        self.title_file = title_file

    def run(self, work):
        import tkinter as tk
        _dpi_aware()
        self.q = queue.Queue(); self.cancel = threading.Event(); self.out = {}
        root = self.root = tk.Tk()
        set_app_icon(root)
        root.title('EmberCheck \u00b7 Print Optimizer for Bambu Studio'); root.configure(bg=BG); root.resizable(False, False)
        root.withdraw()
        root.attributes('-topmost', True)
        px, self.scale = _setup_scaling(root)
        W = px(self.W)
        ff = _font_family()
        f_title = (ff, 13, 'bold'); f_txt = (ff, 10); f_small = (ff, 9)
        P = px(22)
        top = tk.Frame(root, bg=BG); top.pack(fill='x', padx=P, pady=(px(18), 0))
        # bottom row is packed before the middle so it always keeps its space
        bot = tk.Frame(root, bg=BG); bot.pack(fill='x', padx=P, pady=(px(12), px(14)), side='bottom')
        self.btn = RoundButton(bot, 'Cancel', self._cancel, width=px(110), height=px(30), font=f_txt).pack(side='right')
        tk.Label(bot, text='Cancel keeps the original G-code', bg=BG, fg=DIM, font=f_small).pack(side='left')
        lg = logo(top, px(22))
        if lg is not None:
            lg.pack(side='left')
        else:
            d = px(12)
            dot = tk.Canvas(top, width=d, height=d, bg=BG, highlightthickness=0); dot.pack(side='left', pady=(px(3), 0))
            dot.create_oval(1, 1, d - 1, d - 1, fill=GREEN, outline='')
        tk.Label(top, text='EmberCheck', bg=BG, fg=FG, font=f_title).pack(side='left', padx=(px(8), 0))
        self.pct = tk.Label(top, text='0%', bg=BG, fg=GREEN, font=f_title); self.pct.pack(side='right')
        self.sub = tk.Label(root, text=self.title_file, bg=BG, fg=DIM, font=f_small, anchor='w', justify='left',
                            wraplength=W - 2 * P)
        self.sub.pack(fill='x', padx=P, pady=(px(2), px(10)))
        self.bar = ProgressBar(root, width=W - 2 * P, height=px(10)); self.bar.cv.pack(padx=P)
        mid = tk.Frame(root, bg=BG); mid.pack(fill='x', padx=P, pady=(px(10), 0))
        self.elapsed = tk.Label(mid, text='0:00', bg=BG, fg=DIM, font=f_small); self.elapsed.pack(side='right')
        self.stage = tk.Label(mid, text='Starting…', bg=BG, fg=FG, font=f_txt, anchor='w'); self.stage.pack(side='left')
        self.steps = tk.Label(root, text=self._steps_text(None), bg=BG, fg=DIM, font=(ff, 8), anchor='w')
        self.steps.pack(fill='x', padx=P, pady=(px(4), 0))
        root.update_idletasks()
        _center(root, W, root.winfo_reqheight())
        root.deiconify()
        root.protocol('WM_DELETE_WINDOW', self._cancel)
        _win_tweaks(root)
        _shot_hook(root, [self.btn.cv], 'progress')
        self.t0 = time.time()

        def worker():
            try:
                self.out['result'] = work(lambda label, frac, detail='': self.q.put((label, frac, detail)), self.cancel.is_set)
            except BaseException as ex:  # noqa
                self.out['error'] = ex
            self.q.put(None)
        threading.Thread(target=worker, daemon=True).start()
        root.after(50, self._poll)
        root.mainloop()
        pos = self.out.get('pos')
        try:
            root.destroy()
        except Exception:
            pass
        return self.out.get('result'), self.out.get('error'), self.cancel.is_set(), pos

    def _steps_text(self, cur):
        short = ['Parse', 'Thermal', 'Optimize', 'Verify', 'Write']
        if cur not in STAGE_ORDER:
            return '   ›   '.join(short)
        i = STAGE_ORDER.index(cur)
        return '   ›   '.join(('✓ ' + s) if j < i else (('● ' + s) if j == i else s) for j, s in enumerate(short))

    def _poll(self):
        done = False
        try:
            while True:
                item = self.q.get_nowait()
                if item is None:
                    done = True; break
                label, frac, detail = item
                self.bar.set(frac); self.pct.config(text='%d%%' % int(frac * 100))
                self.stage.config(text=label + ('  ·  ' + detail if detail else ''))
                self.steps.config(text=self._steps_text(label))
        except queue.Empty:
            pass
        s = int(time.time() - self.t0)
        self.elapsed.config(text='%d:%02d' % divmod(s, 60))
        if done:
            self.out['pos'] = (self.root.winfo_x(), self.root.winfo_y())
            self.root.quit(); return
        self.root.after(60, self._poll)

    def _cancel(self):
        if not self.cancel.is_set():
            self.cancel.set()
            self.stage.config(text='Cancelling… original G-code will be kept')
            self.btn.set_text('Cancelling…')


