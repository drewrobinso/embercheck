    if d.get('travel_saved_s', 0) >= 0.5:
        info.append('Smart travel order: %s saved (%.0f mm less travel)' % (raw('travel order', d['travel_saved_s']), d.get('travel_saved_mm', 0.0)))
    if d.get('hops_skipped') or d.get('retracts_skipped'):
        info.append('Skipped %d Z-hops and %d retractions on short infill travels: %s saved' % (
            d.get('hops_skipped', 0), d.get('retracts_skipped', 0), raw('hop/retract skip', d.get('hop_saved_s', 0.0))))
    if abs(fs.get('speed/cooling/overhang feeds', 0)) >= 0.5:
        v = fs['speed/cooling/overhang feeds']
        info.append('Speed, cooling and overhang feed changes: %s %s' % (_fmt_dur(v), 'saved' if v > 0 else 'added'))
    if d.get('arcs_on'):
        info.append('Arc fitting: %d arcs replace %d moves' % (d.get('arcs', 0), d.get('arc_segments', 0)))
    elif d.get('arcs_note'):
        info.append('Arc fitting off: %s' % d['arcs_note'])
    if d.get('bambu_time') and not d.get('time_before_s'):
        info.append('Slicer estimate %s · time change is from EmberCheck\'s motion model' % d['bambu_time'])
    if info:
        tk.Label(root, text='\n'.join(info), bg=BG, fg=DIM, font=f_small, anchor='w', justify='left',
                 wraplength=WRAP).pack(fill='x', padx=P, pady=(px(4), 0))
    tk.Label(root, text='Details' if status == 'failed' else 'Recommendations', bg=BG, fg=FG, font=f_bold,
             anchor='w').pack(fill='x', padx=P, pady=(px(12), px(4)))

    # 2) recommendations / failure details: full text, wrapped, in a height-limited scrollable region
    items = []
    if status == 'failed' and d.get('errors'):
        items += [('Reason', e, AMBER) for e in d['errors']]
    items += [(area, _strip(text), GREEN) for area, text in (d.get('recommendations') or [])]
    if not items:
        items = [('Slicer settings', 'Nothing important to change in the slicer for this print.', GREEN)]
    wrap_box = tk.Frame(root, bg=BG); wrap_box.pack(fill='both', expand=True, padx=P, pady=(0, px(6)))
    sb = tk.Scrollbar(wrap_box, orient='vertical')
    cvs = tk.Canvas(wrap_box, bg=BG, highlightthickness=0, bd=0, yscrollcommand=sb.set, width=WRAP)
    sb.config(command=cvs.yview)
    cvs.pack(side='left', fill='both', expand=True)
    inner = tk.Frame(cvs, bg=BG)
    cvs.create_window(0, 0, window=inner, anchor='nw')
    bullet_w = px(16); text_w = WRAP - bullet_w - px(18)   # room for the scrollbar if it is needed
    for area, text, bc in items:
        row = tk.Frame(inner, bg=BG); row.pack(fill='x', pady=px(2), anchor='w')
        tk.Label(row, text='●', bg=BG, fg=bc, font=f_small, width=2, anchor='n').pack(side='left', anchor='n')
        tk.Label(row, text='%s: %s' % (area, text), bg=BG, fg=FG, font=f_small, justify='left', anchor='w',
                 wraplength=text_w).pack(side='left', fill='x')
    inner.update_idletasks()
    rec_h = inner.winfo_reqheight()

    # one line: how to check that the printed file is the optimized one (stamp + docs/verify.md)
    if status == 'optimized':
        try:
            from project_info import REPO_URL
        except Exception:
            REPO_URL = 'https://github.com/drewrobinso/embercheck'
        vurl = REPO_URL + '/blob/main/docs/verify.md'
        hv = tk.Label(root, text='How to verify: the G-code carries an EmberCheck stamp (SHA-256) \u2014 see docs/verify.md',
                      bg=BG, fg=DIM, font=f_small, cursor='hand2', anchor='w', justify='left', wraplength=WRAP)
        hv.pack(fill='x', padx=P, pady=(0, px(6)), side='bottom')
        hv.bind('<Button-1>', lambda _e: webbrowser.open(vurl))
        hv.bind('<Enter>', lambda _e: hv.config(fg=FG)); hv.bind('<Leave>', lambda _e: hv.config(fg=DIM))

    cd = None
    state = {'left': auto_close, 'active': auto_close > 0}

    def close():
        root.destroy()

    def open_report():
        rp = d.get('report')
        if not (rp and os.path.exists(rp)):
            rp = d.get('log_dir')
        if rp and os.path.exists(rp):
            if sys.platform == 'win32':
                os.startfile(rp)  # noqa
            else:
                webbrowser.open('file://' + os.path.abspath(rp))
        state['active'] = False; cd.config(text='')

    # from Bambu Studio: closing the card lets Bambu continue (preview / Print / Send use the optimized file)
    from_bambu = bool(d.get('from_bambu'))
    b_close = RoundButton(bot, 'Continue to Print' if from_bambu else 'Close', close, primary=True,
                          width=px(150) if from_bambu else px(90), height=px(32), font=f_bold).pack(side='right')
    tk.Frame(bot, bg=BG, width=px(8)).pack(side='right')
    b_open = RoundButton(bot, 'Full report' if d.get('report') else 'Log folder', open_report,
                         width=px(104), height=px(32), font=f_txt).pack(side='right')
    # the labels on the left are packed after the buttons, so they shrink first when space is short
    # small, unobtrusive support link (opens the browser only when clicked)
    try:
        from project_info import SUPPORT_URL
    except Exception:
        SUPPORT_URL = None
    if SUPPORT_URL:
        sup = tk.Label(bot, text='\u2665 Support this project', bg=BG, fg=DIM, font=f_small, cursor='hand2')
        sup.pack(side='left', padx=(0, px(10)))
        sup.bind('<Button-1>', lambda _e: webbrowser.open(SUPPORT_URL))
        sup.bind('<Enter>', lambda _e: sup.config(fg=FG)); sup.bind('<Leave>', lambda _e: sup.config(fg=DIM))
    cd = tk.Label(bot, text='', bg=BG, fg=DIM, font=f_small, anchor='w'); cd.pack(side='left', fill='x', expand=True)

    # 3) size the window from what it actually needs, capped to the screen; the list scrolls if it must
    cvs.config(height=rec_h)
    root.update_idletasks()
    need = root.winfo_reqheight()
    cap = _usable_height(root) - px(10)
    if need > cap:
        cvs.config(height=max(px(60), rec_h - (need - cap)))
        sb.pack(side='right', fill='y')
        root.update_idletasks()
        need = min(root.winfo_reqheight(), cap)
    cvs.config(scrollregion=(0, 0, WRAP, rec_h))
    def wheel(e):
        if sb.winfo_ismapped():
            cvs.yview_scroll(-1 if (getattr(e, 'delta', 0) > 0 or getattr(e, 'num', 0) == 4) else 1, 'units')
    for w in (root,):
        w.bind_all('<MouseWheel>', wheel); w.bind_all('<Button-4>', wheel); w.bind_all('<Button-5>', wheel)
    if pos:
        pos = (max(0, pos[0] - px(10)), max(0, pos[1] - px(120)))
    _center(root, max(W, root.winfo_reqwidth()), need, pos)
    root.deiconify()
    _shot_hook(root, [b_open.cv, b_close.cv], 'summary-' + status)

    def stop_timer(_e=None):
        if state['active']:
            state['active'] = False; cd.config(text='')
    root.bind('<Button-1>', stop_timer, add='+'); root.bind('<Key>', stop_timer, add='+')

    def tick():
        if not state['active']:
            return
        if state['left'] <= 0:
            close(); return
        cd.config(text=('Continues in %ds' if d.get('from_bambu') else 'Closes in %ds') % state['left'])
        state['left'] -= 1
        root.after(1000, tick)
