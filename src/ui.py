def _fmt_s(sec):
    sec = abs(sec)
    return '%d s' % round(sec) if sec < 90 else ('%d min' % round(sec / 60) if sec < 5400 else '%.1f h' % (sec / 3600))


def _fmt_dur(sec):
    from report import fmt_dur
    return fmt_dur(sec)


def _fmt_delta(sec):
    from report import fmt_delta
    return fmt_delta(sec)


def _time_line(b, a):
    from report import time_line
    return time_line(b, a)


def choose_printers(avail, pre, title='EmberCheck \u00b7 Bambu Studio presets'):
    """Checkbox list of printer models. avail = [(printer_model, short, nozzles)], pre = models to pre-check.
    Returns the chosen printer_model list, or None if cancelled."""
    import tkinter as tk
    _dpi_aware()
    root = tk.Tk(); root.title(title); root.configure(bg=BG); root.resizable(False, False)
    set_app_icon(root)
    root.withdraw()
    px, _ = _setup_scaling(root)
    ff = _font_family(); P = px(22)
    tk.Label(root, text='Which printers do you use?', bg=BG, fg=FG, font=(ff, 13, 'bold'), anchor='w').pack(fill='x', padx=P, pady=(px(18), px(2)))
    tk.Label(root, text='EmberCheck adds "EmberCheck Balanced / Speed / Quality" process presets for every nozzle of each checked printer. '
             'Printers set up in Bambu Studio are pre-checked.', bg=BG, fg=DIM, font=(ff, 9), anchor='w', justify='left',
             wraplength=px(420)).pack(fill='x', padx=P, pady=(0, px(10)))
    box = tk.Frame(root, bg=BG); box.pack(fill='x', padx=P)
    vars_ = []
    for i, (model, short, noz) in enumerate(avail):
        v = tk.IntVar(value=1 if model in pre else 0)
        nz = ', '.join(sorted({mm.group(1) for n in noz for mm in [re.search(r'(\d+(?:\.\d+)?) nozzle', n)] if mm}, key=float))
        cb = tk.Checkbutton(box, text='%s%s' % (re.sub(r'^Bambu Lab ', '', model), ('  (%s mm)' % nz) if nz else ''), variable=v,
                            bg=BG, fg=FG, selectcolor=CARD, activebackground=BG, activeforeground=FG, font=(ff, 10), anchor='w',
                            highlightthickness=0, bd=0)
        cb.grid(row=i // 2, column=i % 2, sticky='w', padx=(0, px(18)), pady=px(2))
        vars_.append((model, v))
    res = {'v': None}
    bot = tk.Frame(root, bg=BG); bot.pack(fill='x', padx=P, pady=(px(16), px(16)))

    def ok():
        res['v'] = [m for m, v in vars_ if v.get()]; root.destroy()

    def cancel():
        root.destroy()
    b_ok = RoundButton(bot, 'Add presets', ok, primary=True, width=px(120), height=px(32), font=(ff, 10, 'bold')).pack(side='right')
    tk.Frame(bot, bg=BG, width=px(8)).pack(side='right')
    b_c = RoundButton(bot, 'Cancel', cancel, width=px(90), height=px(32), font=(ff, 10)).pack(side='right')
    root.update_idletasks()
    _center(root, max(px(470), root.winfo_reqwidth()), root.winfo_reqheight())
    root.deiconify()
    _shot_hook(root, [b_ok.cv, b_c.cv], 'printers')
    root.protocol('WM_DELETE_WINDOW', cancel)
    _win_tweaks(root)
    root.mainloop()
    return res['v']


def _strip(s):
    s = re.sub(r'<[^>]+>', '', s)
    return _html.unescape(s)


