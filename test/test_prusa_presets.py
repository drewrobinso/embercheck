"""Self-contained test for src/prusa_presets.py (PrusaSlicer print presets): vendor-bundle inherits flattening,
C-style string escaping, user-preset bases, never overwriting presets EmberCheck did not create, repointing edited
presets, uninstall with backup, status text. Run: python test/test_prusa_presets.py"""
import json, os, sys, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src'))
import prusa_presets as pp

BUNDLE = r'''[vendor]
name = Creality
config_version = 2.0.0

[print:*common*]
layer_height = 0.2
perimeters = 2
infill_speed = 40
notes =
post_process =
compatible_printers_condition = printer_notes=~/.*PRINTER_VENDOR_CREALITY.*/

[print:*0.20mm*]
layer_height = 0.2
infill_speed = 60

[print:*fast*]
infill_speed = 80
renamed_from = "Old name"

[print:0.20 mm NORMAL (0.4 mm nozzle) @CREALITY]
inherits = *common*; *0.20mm*
perimeter_speed = 40

[print:0.20 mm FAST @CREALITY]
inherits = *0.20mm*; *fast*
'''
CMD = r'"C:\Program Files\EmberCheck\EmberCheck.exe" --goal {goal}'
BASE = '0.20 mm NORMAL (0.4 mm nozzle) @CREALITY'
fails = []


def check(cond, msg):
    print(('ok   ' if cond else 'FAIL ') + msg)
    if not cond:
        fails.append(msg)


def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)


def main():
    q = lambda m: None
    # escaping round trip
    vals = [r'"C:\Program Files\x.exe" --goal speed', 'plain', 'a;b']
    check(pp.unescape_strings(pp.escape_strings(vals)) == vals, 'escape/unescape round trip')
    check(pp.unescape_strings('*a*; *b*') == ['*a*', '*b*'], 'inherits list split')

    d = tempfile.mkdtemp(); app = tempfile.mkdtemp(); man = os.path.join(app, 'm.json'); bk = os.path.join(app, 'bk')
    w(os.path.join(d, 'vendor', 'Creality.ini'), BUNDLE)
    check(pp.install(CMD, d, man, q)['status'] == 'noprint', 'no PrusaSlicer.ini selection -> noprint')
    w(os.path.join(d, 'PrusaSlicer.ini'), '[presets]\nprint = %s\nprinter = Creality Ender-3 V2 Neo (0.4 mm nozzle)\n' % BASE)

    secs = pp.read_ini(os.path.join(d, 'vendor', 'Creality.ini'))
    fl = pp.flatten(secs, 'print', BASE)
    check(fl['infill_speed'] == '60' and fl['perimeters'] == '2' and fl['perimeter_speed'] == '40', 'later parent wins, own keys win')
    check('inherits' not in fl and 'renamed_from' not in pp.flatten(secs, 'print', '0.20 mm FAST @CREALITY'), 'inherits/renamed_from dropped')

    st = pp.install(CMD, d, man, q)
    check(st['status'] == 'ok' and len(st['written']) == 3, 'three presets written for the selected profile')
    names = [pp.preset_name(BASE, g) for g in ('Balanced', 'Speed', 'Quality')]
    p_bal = os.path.join(d, 'print', names[0] + '.ini')
    cfg = pp.read_ini(p_bal)['']
    check(cfg['inherits'] == BASE, 'inherits = base')
    check(cfg['infill_speed'] == '60' and cfg['compatible_printers_condition'].startswith('printer_notes'), 'full parent settings + visibility condition copied')
    scr = pp.unescape_strings(cfg['post_process'])
    check(scr == [r'"C:\Program Files\EmberCheck\EmberCheck.exe" --goal balanced'], 'post_process escaped, goal filled in')
    check(pp.MARK in cfg['notes'], 'marker in notes')
    check('--goal speed' in pp.read_ini(os.path.join(d, 'print', names[1] + '.ini'))['']['post_process'], 'speed preset runs --goal speed')
    check('EmberCheck' in pp.status_text(st) and 'Restart PrusaSlicer' in pp.status_text(st), 'status text')

    # selected profile is one of ours -> same base; re-install is idempotent
    w(os.path.join(d, 'PrusaSlicer.ini'), '[presets]\nprint = %s\n' % names[1])
    st = pp.install(CMD, d, man, q)
    check(st['bases'] == [BASE] and len(st['written']) == 3, 'EmberCheck preset selected -> same base')

    # a user preset as base, with its own post-processing script kept
    up = 'My Ender tweaks'
    w(os.path.join(d, 'print', up + '.ini'), '# generated by PrusaSlicer\ninherits = %s\ninfill_speed = 70\npost_process = "C:\\\\tools\\\\other.py"\nnotes = mine\n' % BASE)
    st = pp.install(CMD, d, man, q, bases=[up])
    c2 = pp.read_ini(os.path.join(d, 'print', pp.preset_name(up, 'Speed') + '.ini'))['']
    check(c2['inherits'] == BASE and c2['infill_speed'] == '70', 'user preset base: its settings, its parent link')
    check(pp.unescape_strings(c2['post_process'])[0] == 'C:\\tools\\other.py' and len(pp.unescape_strings(c2['post_process'])) == 2,
          'existing post-processing script kept before ours')
    check(c2['notes'].startswith('mine\\n\\n'), 'user notes kept')

    # foreign preset with our name is never overwritten
    foreign = os.path.join(d, 'print', pp.preset_name('0.20 mm FAST @CREALITY', 'Quality') + '.ini')
    w(foreign, 'infill_speed = 1\n')
    st = pp.install(CMD, d, man, q, bases=['0.20 mm FAST @CREALITY'])
    check(open(foreign).read() == 'infill_speed = 1\n' and len(st['written']) == 2, 'foreign same-named preset untouched')

    # user edits one of ours -> reinstall with a new exe path only repoints
    with open(p_bal, 'a', encoding='utf-8') as f:
        f.write('fill_density = 42%\n')
    CMD2 = CMD.replace('Program Files', 'Apps')
    st = pp.install(CMD2, d, man, q, bases=[BASE])
    c3 = pp.read_ini(p_bal)['']
    check(names[0] in st['kept'] and c3['fill_density'] == '42%' and 'Apps' in c3['post_process'], 'edited preset kept, exe repointed')
    check('Apps' in pp.read_ini(os.path.join(d, 'print', names[1] + '.ini'))['']['post_process'], 'unedited preset rewritten')
    check('nope' not in pp.status_text({'status': 'noprusa'}) and 'not found' in pp.status_text({'status': 'noprusa'}), 'noprusa text')

    # uninstall: only ours, edited one backed up, foreign + base user preset kept
    n = pp.remove(d, man, q, backup_dir=bk)
    left = sorted(os.listdir(os.path.join(d, 'print')))
    check(n == 8, 'removed our 8 presets (got %d)' % n)
    check(left == sorted([up + '.ini', os.path.basename(foreign)]), 'left only user files: %s' % left)
    check(os.path.exists(os.path.join(bk, names[0] + '.ini')), 'edited preset backed up')
    check(not os.path.exists(man), 'manifest removed')
    check(pp.install(CMD, os.path.join(d, 'missing'), None, q)['status'] == 'noprusa', 'no PrusaSlicer -> noprusa')
    print('\n%s' % ('ALL PASS' if not fails else '%d FAILED' % len(fails)))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
