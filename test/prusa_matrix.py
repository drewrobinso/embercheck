"""PrusaSlicer / Marlin goal matrix (run: python3 test/prusa_matrix.py [--quick]).

Cases: test/fixtures/prusa/ender3v2neo_tower_*.gcode.gz (PrusaSlicer 2.9.7, Creality Ender 3 V2 Neo profile; see
make_fixtures.sh) and, when present, the local sample test/out/prusa/ender3v2neo_sample.gcode (not in the repo).

For every case x goal (and a strict no-reorder variant checked line by line):
  * the built-in validator and test/verify.py pass (extrusion per layer exact, start/end/temperatures unchanged)
  * SPEED never slower than the original, BALANCED at most +2 %, ORDER speed <= balanced <= quality
  * Marlin-safe output: acceleration lines use the flavour's letter (Marlin 2: M204 P, legacy Marlin: M204 S),
    no Bambu-only commands or comments are added, the output is still read as PrusaSlicer G-code
  * the stamp sits right after PrusaSlicer's '; generated by' line and its SHA-256 matches
  * M73 progress (when the slicer wrote it) is rewritten and never goes backwards
Writes test/results/prusa_matrix.md / .json."""
import os, sys, json, gzip, re, subprocess, tempfile
from concurrent.futures import ProcessPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'src'))
FIX = os.path.join(HERE, 'fixtures', 'prusa')
import report as R  # noqa: E402  (same time format as the card)
SAMPLE = os.path.join(HERE, 'out', 'prusa', 'ender3v2neo_sample.gcode')
GOALS = ['speed', 'balanced', 'quality']
EPS = 0.05
BAMBU_ONLY = re.compile(r'^(M620|M621|M622|M623|M991|M971|M1004|M993|M73 L|; FEATURE:|; CHANGE_LAYER|; LINE_WIDTH:)')


def cases(quick=False):
    out = []
    for fn in sorted(os.listdir(FIX)):
        if fn.endswith('.gcode.gz'):
            out.append((fn[:-9], os.path.join(FIX, fn)))
    if os.path.exists(SAMPLE) and not quick:
        out.append(('ender3v2neo_sample', SAMPLE))
    return out


def read(path):
    if path.endswith('.gz'):
        with gzip.open(path, 'rt', encoding='utf-8', newline='') as f:
            return f.read()
    with open(path, encoding='utf-8', newline='') as f:
        return f.read()


def run(args):
    name, path, goal, variant, outdir = args
    import embercheck as B, stamp
    from optimizer import Settings
    from gcode_model import GcodeFile
    text = read(path)
    kw = {'reorder': False} if variant == 'no_reorder' else {}
    st = Settings(goal=goal, **kw); st.dry_run = False
    new, html, s = B.process_text(text, st, name, log=lambda m: None)
    res = {'case': name, 'goal': goal, 'variant': variant, 'errors': list(s['errors']), 'dt_pct': s['dt_pct'],
           'before_s': s.get('time_before_s'), 'after_s': s.get('time_after_s'), 'time_line': s.get('time_line'),
           'slicer_time': s.get('bambu_time'), 'hot': (s['hot_before'], s['hot_after']), 'ov': s['overhangs_slowed'],
           'hops': s['hops_skipped'], 'retracts': s['retracts_skipped'], 'hop_s': s['hop_saved_s'],
           'travel_s': s['travel_saved_s'], 'acc_s': s['acc_saved_s'], 'feeds': s['est'].get('f_changed', 0),
           'm73_rewritten': None, 'checks': [], 'verify': None, 'slicer': s.get('slicer')}
    chk = res['checks']
    if not new:
        chk.append('no output (%s)' % ('; '.join(s['errors']) or 'nothing to change'))
        return res
    src = os.path.join(outdir, '%s.orig.gcode' % name)
    if not os.path.exists(src):
        open(src, 'w', encoding='utf-8', newline='').write(text)
    o = os.path.join(outdir, '%s.%s.%s.gcode' % (name, goal, variant))
    open(o, 'w', encoding='utf-8', newline='').write(new)
    r = subprocess.run([sys.executable, os.path.join(HERE, 'verify.py'), src, o] + (['--reordered'] if variant != 'no_reorder' else []),
                       capture_output=True, text=True)
    res['verify'] = (r.stdout.strip().splitlines() or ['?'])[-1]
    if res['verify'] != 'PASS':
        chk.append('verify.py: ' + ' | '.join(l for l in r.stdout.splitlines() if 'unexpected' in l or 'identical' in l or 'FAIL' in l))
    g2 = GcodeFile(stamp.strip(new)[0])
    if g2.dialect.name != 'prusaslicer': chk.append('output not read as PrusaSlicer G-code')
    flavor = g2.dialect.flavor
    want = 'P' if flavor == 'marlin2' else 'S'
    old = set(text.splitlines()); added = [l for l in new.splitlines() if l not in old]
    acc_added = [l for l in added if l.startswith('M204')]
    if any(not re.match(r'^M204 %s\d+$' % want, l) for l in acc_added):
        chk.append('wrong M204 form for %s: %s' % (flavor, acc_added[:2]))
    bad = [l for l in added if BAMBU_ONLY.match(l)]
    if bad: chk.append('Bambu-only lines added: %s' % bad[:3])
    lines = new.splitlines()
    if not (lines[0].startswith('; generated by PrusaSlicer') and lines[1] == stamp.BEGIN):
        chk.append('stamp not right after the "generated by" line')
    ok, msg = stamp.check_text(new)
    if not ok: chk.append('stamp: ' + msg)
    m73o = [l for l in text.splitlines() if l.startswith('M73 P')]
    if m73o:
        m73n = [l for l in lines if l.startswith('M73 P')]
        res['m73_rewritten'] = sum(1 for a, b in zip(m73o, m73n) if a != b)
        P = [int(re.search(r'P(\d+)', l).group(1)) for l in m73n]
        if any(b < a for a, b in zip(P, P[1:])): chk.append('M73 P goes backwards')
        if len(m73n) != len(m73o): chk.append('M73 line count changed')
    if goal == 'speed' and res['dt_pct'] > EPS: chk.append('speed goal slower than original (%+.2f%%)' % res['dt_pct'])
    if goal == 'balanced' and res['dt_pct'] > 2.0 + EPS: chk.append('balanced goal above +2%% (%+.2f%%)' % res['dt_pct'])
    if res['errors']: chk.append('validator: %s' % res['errors'])
    return res


def main():
    quick = '--quick' in sys.argv
    outdir = tempfile.mkdtemp(prefix='prusa_matrix_')
    jobs = [(n, p, g, v, outdir) for n, p in cases(quick) for g in GOALS for v in (['full'] if quick else ['full', 'no_reorder'])]
    with ProcessPoolExecutor(int(os.environ.get('NP', os.cpu_count() or 4))) as ex:
        res = list(ex.map(run, jobs))
    fails = []
    by = {(r['case'], r['goal'], r['variant']): r for r in res}
    for n, _ in cases(quick):
        for v in (['full'] if quick else ['full', 'no_reorder']):
            t = [by[(n, g, v)]['dt_pct'] for g in GOALS]
            if not (t[0] <= t[1] + EPS and t[1] <= t[2] + EPS):
                fails.append('%s %s: goal order speed<=balanced<=quality broken %s' % (n, v, t))
    for r in res:
        fails += ['%s %s %s: %s' % (r['case'], r['goal'], r['variant'], c) for c in r['checks']]
    fmt = lambda s: '-' if s is None else R.fmt_dur(s)
    md = ['# PrusaSlicer / Marlin goal matrix', '',
          'Raw times: PrusaSlicer\'s own estimate from the G-code footer (before), scaled by EmberCheck\'s motion model (after).', '',
          '| Print | Goal | Variant | Before | After | Change | Hop/retract skip | Travel order | Retracts / Z-hops skipped | Feeds changed | M73 rewritten | verify.py | Checks |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in res:
        md.append('| %s | %s | %s | %s | %s | %+.2f%% | %s | %s | %d / %d | %d | %s | %s | %s |' % (
            r['case'], r['goal'], r['variant'], fmt(r['before_s']), fmt(r['after_s']), r['dt_pct'], fmt(r['hop_s']), fmt(r['travel_s']),
            r['retracts'], r['hops'], r['feeds'], '-' if r['m73_rewritten'] is None else r['m73_rewritten'], r['verify'],
            'PASS' if not r['checks'] else '; '.join(r['checks'])))
    md += ['', 'Result: **%s**' % ('PASS' if not fails else 'FAIL')] + ['- ' + f for f in fails]
    os.makedirs(os.path.join(HERE, 'results'), exist_ok=True)
    open(os.path.join(HERE, 'results', 'prusa_matrix.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    json.dump(res, open(os.path.join(HERE, 'results', 'prusa_matrix.json'), 'w'), indent=1)
    print('\n'.join(md))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
